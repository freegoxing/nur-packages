#! /usr/bin/env nix-shell
#! nix-shell -i bash --pure --keep GITHUB_TOKEN -p nix git curl cacert nix-prefetch-git jq
# shellcheck shell=bash

set -euo pipefail

cd "$(readlink -e "$(dirname "${BASH_SOURCE[0]}")")"

sign_url() {
  # https://github.com/flathub/com.qq.QQ/issues/274#issuecomment-5512982615
  curl -fsS -X POST "https://im.qq.com/http2rpc/gotrpc/noauth/trpc.qqntv2.urlsign.UrlSign/GetSign" \
    -H "Content-Type: application/json" \
    -H 'x-oidb: {"uint32_command":"0x9b8e","uint32_service_type":1}' \
    -d "{\"url\":\"$1\"}" | jq -er '.data.url'
}

# linux

linux_payload=$(curl https://cdn-go.cn/qq-web/im.qq.com_new/latest/rainbow/linuxConfig.js | grep -oP "var params= \K\{.*\}(?=;)")
linux_version=$(jq -r .version <<<"$linux_payload")-$(jq -r .updateDate <<<"$linux_payload")

linux_x86_64_url=$(jq -r .x64DownloadUrl.deb <<<"$linux_payload")

linux_x86_64_hash=$(nix-prefetch-url "$(sign_url "$linux_x86_64_url")")

# use friendlier hashes
linux_x86_64_hash=$(nix --extra-experimental-features nix-command hash convert --to sri --hash-algo sha256 "$linux_x86_64_hash")

cat >sources.nix <<EOF
# Generated by ./update.sh - do not update manually!
{ }:
{
  x86_64-linux = {
    version = "$linux_version";
    url = "$linux_x86_64_url";
    hash = "$linux_x86_64_hash";
  };
}
EOF
